#!/usr/bin/env python3
"""
Copia C98_GET y c98_geo desde MariaDB local hacia Supabase (Postgres).

- El local es SOLO LECTURA: solo se ejecutan SELECT / information_schema.
- Destino: la URL de SUPABASE_DB_URL en ../.env.supabase (archivo fuera de git).
- Cada BD queda en su propio schema de Postgres: c98_get y c98_geo.
- Se omiten las tablas de respaldo (*bkp*, bak_*).

Uso:
  python tools/supabase/copy_datos.py --schema-only          # solo crea tablas
  python tools/supabase/copy_datos.py                        # crea y copia datos
  python tools/supabase/copy_datos.py --only c98_geo         # una sola BD
  python tools/supabase/copy_datos.py --reset                # borra los schemas EN SUPABASE y recrea
"""
import argparse, io, os, re, sys, time
import pymysql
from conexion import conectar_mysql, conectar_pg

SCHEMAS = ["c98_get", "c98_geo"]
SKIP = re.compile(r"(bkp|^bak_)", re.I)
CHUNK = 5000


def map_type(col_type, data_type):
    t = col_type.lower()
    if t.startswith("tinyint"):   return "smallint"
    if t.startswith("smallint"):  return "integer" if "unsigned" in t else "smallint"
    if t.startswith("mediumint"): return "integer"
    if t.startswith("int"):       return "bigint" if "unsigned" in t else "integer"
    if t.startswith("bigint"):    return "bigint"
    m = re.match(r"(?:decimal|numeric)\((\d+),(\d+)\)", t)
    if m:                         return f"numeric({m.group(1)},{m.group(2)})"
    if t.startswith(("float", "double")): return "double precision"
    m = re.match(r"varchar\((\d+)\)", t)
    if m:                         return f"varchar({m.group(1)})"
    m = re.match(r"char\((\d+)\)", t)
    if m:                         return f"char({m.group(1)})"
    if "text" in t:               return "text"
    if t.startswith("datetime"):  return "timestamp"
    if t.startswith("timestamp"): return "timestamptz"
    if t == "date":               return "date"
    if t.startswith("enum"):      return "text"
    if t == "multipolygon":       return "extensions.geometry(MultiPolygon,4326)"
    if t == "json":               return "jsonb"
    raise ValueError(f"Tipo no mapeado: {col_type}")


def q(name):
    return '"' + name.replace('"', '""') + '"'


def esc(v):
    """Formato COPY text de Postgres."""
    if v is None:
        return r"\N"
    if isinstance(v, bytes):
        v = v.decode("utf-8", "replace")
    if isinstance(v, bool):
        return "1" if v else "0"
    s = str(v).replace("\x00", "")
    if s.startswith("0000-00-00"):      # fecha cero de MariaDB -> NULL en Postgres
        return r"\N"
    return s.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--schema-only", action="store_true")
    ap.add_argument("--only", choices=SCHEMAS)
    ap.add_argument("--reset", action="store_true", help="DROP SCHEMA ... CASCADE en Supabase")
    ap.add_argument("--tables", help="lista separada por comas (solo esas tablas)")
    args = ap.parse_args()

    my = conectar_mysql()
    pg = conectar_pg()
    pc = pg.cursor()
    mc = my.cursor()

    pc.execute("set statement_timeout = 0")
    pc.execute("create extension if not exists postgis with schema extensions")
    wanted = [args.only] if args.only else SCHEMAS
    only_tables = set(args.tables.split(",")) if args.tables else None

    for schema in wanted:
        if args.reset:
            print(f"[reset] DROP SCHEMA {schema} CASCADE (Supabase)")
            pc.execute(f"drop schema if exists {schema} cascade")
        pc.execute(f"create schema if not exists {schema}")

        mc.execute("select table_name from information_schema.tables "
                   "where table_schema=%s and table_type='BASE TABLE' order by table_name", (schema,))
        tables = [r[0] for r in mc.fetchall() if not SKIP.search(r[0])]
        if only_tables:
            tables = [t for t in tables if t in only_tables]

        # ---------- DDL ----------
        for t in tables:
            mc.execute("select column_name,column_type,data_type,is_nullable,extra,column_default "
                       "from information_schema.columns where table_schema=%s and table_name=%s "
                       "order by ordinal_position", (schema, t))
            cols = mc.fetchall()
            mc.execute("select column_name from information_schema.key_column_usage "
                       "where table_schema=%s and table_name=%s and constraint_name='PRIMARY' "
                       "order by ordinal_position", (schema, t))
            pk = [r[0] for r in mc.fetchall()]
            defs = []
            for name, ctype, dtype, nullable, extra, _d in cols:
                pt = map_type(ctype, dtype)
                d = f"{q(name)} {pt}"
                if "auto_increment" in (extra or ""):
                    d += " generated by default as identity"
                if nullable == "NO":
                    d += " not null"
                defs.append(d)
            if pk:
                defs.append("primary key (" + ",".join(q(c) for c in pk) + ")")
            pc.execute(f"drop table if exists {schema}.{q(t)} cascade")
            pc.execute(f"create table {schema}.{q(t)} (\n  " + ",\n  ".join(defs) + "\n)")
        print(f"[{schema}] {len(tables)} tablas creadas")

        if args.schema_only:
            continue

        # ---------- datos ----------
        for t in tables:
            mc.execute("select column_name,column_type,data_type from information_schema.columns "
                       "where table_schema=%s and table_name=%s order by ordinal_position", (schema, t))
            cols = mc.fetchall()
            sel = []
            for name, ctype, _ in cols:
                if ctype.lower() == "multipolygon":
                    sel.append(f"CONCAT('SRID=4326;', ST_AsText(`{name}`)) AS `{name}`")
                else:
                    sel.append(f"`{name}`")
            colnames = ",".join(q(c[0]) for c in cols)
            t0 = time.time()
            cur = my.cursor(pymysql.cursors.SSCursor)
            cur.execute(f"select {','.join(sel)} from `{schema}`.`{t}`")
            total = 0
            chunk = 100 if any(c[1].lower() == "multipolygon" for c in cols) else CHUNK
            while True:
                rows = cur.fetchmany(chunk)
                if not rows:
                    break
                buf = io.StringIO()
                for r in rows:
                    buf.write("\t".join(esc(v) for v in r) + "\n")
                buf.seek(0)
                pc.copy_expert(f"copy {schema}.{q(t)} ({colnames}) from stdin", buf)
                total += len(rows)
            cur.close()
            # sincronizar identidad
            for name, ctype, _ in cols:
                pass
            pc.execute("select a.attname from pg_attribute a join pg_class c on c.oid=a.attrelid "
                       "join pg_namespace n on n.oid=c.relnamespace "
                       "where n.nspname=%s and c.relname=%s and a.attidentity<>''", (schema, t))
            for (idcol,) in pc.fetchall():
                pc.execute(f"select setval(pg_get_serial_sequence('{schema}.{q(t)}','{idcol}'), "
                           f"coalesce((select max({q(idcol)}) from {schema}.{q(t)}),1))")
            print(f"[{schema}.{t}] {total} filas en {time.time()-t0:.1f}s")

    print("Listo.")


if __name__ == "__main__":
    main()
